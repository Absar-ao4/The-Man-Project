package com.example.fitapp.workout.generator;

import com.example.fitapp.ai.AiGateway;
import com.example.fitapp.ai.AiLogService;
import com.example.fitapp.ai.AiModelClient.AiReply;
import com.example.fitapp.ai.AiModelClient.AiRequest;
import com.example.fitapp.common.ApiException;
import com.example.fitapp.common.ErrorCode;
import com.example.fitapp.config.AnthropicProperties;
import com.example.fitapp.workout.generator.GeneratorTypes.GeneratedDay;
import com.example.fitapp.workout.generator.GeneratorTypes.GeneratedExercise;
import com.example.fitapp.workout.generator.GeneratorTypes.GeneratedPlan;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import java.util.ArrayList;
import java.util.List;
import org.springframework.stereotype.Component;

/**
 * Explains a plan through the shared AI gateway (same client, same daily budget). The model is forced
 * to answer through one tool, so the reply is structured data and never free text that could carry
 * instructions to the app.
 *
 * <p>Only the generated plan goes to the model (exercise names, sets, reps, rest). No name, email,
 * body data or user id is sent, and the plan is built from enums and library names, not user text.
 */
@Component
public class AnthropicPlanExplainerClient implements PlanExplainerClient {

    private static final String TOOL = "report_explanation";
    private static final int MAX_SUGGESTIONS = 3;

    private static final String SYSTEM_PROMPT =
            "You are a friendly strength coach. You are given a workout plan that was generated by fixed rules. "
                    + "Explain in plain language, in under 120 words, why it is built this way (the split, the volume and the rep ranges). "
                    + "Then give two or three short, practical tweak suggestions the lifter could consider. "
                    + "Never claim medical knowledge, never tell the lifter to train through pain, and do not invent exercises that are not in the plan. "
                    + "Always answer by calling the report_explanation tool.";

    private final AiGateway gateway;
    private final AiLogService logs;
    private final AnthropicProperties props;
    private final ObjectMapper mapper;

    public AnthropicPlanExplainerClient(AiGateway gateway, AiLogService logs, AnthropicProperties props, ObjectMapper mapper) {
        this.gateway = gateway;
        this.logs = logs;
        this.props = props;
        this.mapper = mapper;
    }

    @Override
    public Explanation explain(GeneratedPlan plan) {
        if (!props.configured()) {
            throw new ApiException(ErrorCode.UPSTREAM_UNAVAILABLE, "AI explanations are not set up on this server");
        }
        long started = System.currentTimeMillis();
        try {
            AiReply reply = gateway.call(request(plan));
            Explanation explanation = parse(reply.toolInput());
            logs.log(null, "EXPLAIN", reply.model(), reply.inputTokens(), reply.outputTokens(), reply.costUsd(), 0, null, false, "OK", System.currentTimeMillis() - started);
            return explanation;
        } catch (ApiException e) {
            logs.log(null, "EXPLAIN", props.explainModelOrDefault(), 0, 0, java.math.BigDecimal.ZERO, 0, null, false, "ERROR", System.currentTimeMillis() - started);
            throw e;
        }
    }

    private AiRequest request(GeneratedPlan plan) {
        ObjectNode schema = mapper.createObjectNode();
        schema.put("type", "object");
        ObjectNode properties = schema.putObject("properties");
        properties.putObject("explanation").put("type", "string");
        ObjectNode suggestions = properties.putObject("suggestions");
        suggestions.put("type", "array");
        suggestions.put("maxItems", MAX_SUGGESTIONS);
        suggestions.putObject("items").put("type", "string");
        schema.putArray("required").add("explanation").add("suggestions");

        ObjectNode text = mapper.createObjectNode();
        text.put("type", "text");
        text.put("text", describe(plan));
        return new AiRequest(
                props.explainModelOrDefault(),
                SYSTEM_PROMPT,
                List.of(text),
                TOOL,
                "Report the explanation and the tweak suggestions.",
                schema,
                700);
    }

    /** The plan as plain text: structure and numbers only. */
    static String describe(GeneratedPlan plan) {
        StringBuilder sb = new StringBuilder();
        sb.append("Goal: ").append(plan.goal()).append(", level: ").append(plan.level()).append(", split: ").append(plan.split());
        sb.append(", ").append(plan.daysPerWeek()).append(" days a week, about ").append(plan.sessionMinutes()).append(" minutes per session.\n");
        for (GeneratedDay day : plan.days()) {
            sb.append("\n").append(day.name()).append(" (").append(day.focus()).append("):\n");
            for (GeneratedExercise e : day.exercises()) {
                sb.append("- ").append(e.exerciseName()).append(": ").append(e.sets()).append(" sets of ").append(e.repMin());
                if (e.repMax() != e.repMin()) {
                    sb.append("-").append(e.repMax());
                }
                sb.append(" reps, rest ").append(e.restSeconds()).append(" s\n");
            }
        }
        sb.append("\nWeekly sets per muscle (target / planned):\n");
        plan.weeklySets().forEach(v -> sb.append("- ").append(v.muscle()).append(": ").append(v.target()).append(" / ").append(v.actual()).append("\n"));
        return sb.toString();
    }

    /** [input] is what the model put into the tool. */
    Explanation parse(JsonNode input) {
        if (input != null && input.isObject()) {
            String text = input.path("explanation").asText("").trim();
            List<String> ideas = new ArrayList<>();
            if (input.path("suggestions") instanceof ArrayNode items) {
                for (JsonNode item : items) {
                    String idea = item.asText("").trim();
                    if (!idea.isEmpty() && ideas.size() < MAX_SUGGESTIONS) {
                        ideas.add(idea);
                    }
                }
            }
            if (!text.isEmpty()) {
                return new Explanation(text, ideas);
            }
        }
        throw new ApiException(ErrorCode.UPSTREAM_UNAVAILABLE, "The AI service gave an answer that could not be used");
    }
}
